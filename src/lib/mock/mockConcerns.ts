function initials(name: string) {
  return name
    .split(' ')
    .map((p) => p[0])
    .join('')
    .slice(0, 2)
    .toUpperCase();
}

function ts(date: string, time: string) {
  return new Date(`${date}T${time}:00`).getTime();
}

function timeline(
  status: ParentConcern['status'],
  openedAt: string,
): ConcernTimelineEvent[] {
  const steps: ConcernTimelineEvent[] = [
    { step: 'Open', label: 'Case opened', at: openedAt, completed: true },
    {
      step: 'In Progress',
      label: 'In progress',
      completed: status === 'In Progress' || status === 'Resolved',
      at: status === 'In Progress' || status === 'Resolved' ? 'Staff update' : undefined,
    },
    {
      step: 'Resolved',
      label: 'Resolved',
      completed: status === 'Resolved',
      at: status === 'Resolved' ? 'Follow-up complete' : undefined,
    },
  ];
  return steps;
}

