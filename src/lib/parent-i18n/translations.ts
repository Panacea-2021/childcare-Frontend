export const PARENT_TRANSLATIONS: Partial<Record<ParentLanguage, ParentMessages>> = {
  English: EN,
  'English (UK)': EN,
  Dutch: NL,
  Hindi: HI,
  French: FR,
  German: DE,
  Spanish: ES,
  Arabic: AR,
  Portuguese: PT,
  Italian: IT,
  Tamil: TA,
  Telugu: TE,
  Indonesian: ID,
};

export function getParentMessages(language: ParentLanguage): ParentMessages {
  return PARENT_TRANSLATIONS[language] ?? EN;
}

export function translateParent(
  language: ParentLanguage,
  key: keyof ParentMessages,
): string {
  const pack = getParentMessages(language);
  return pack[key] ?? EN[key] ?? key;
}
