function staffDepartment(role: string): StaffDepartment {
  if (/admin|principal|super|center head|finance/i.test(role)) return 'Administration';
  if (/teacher/i.test(role)) return 'Teaching';
  return 'Management';
}

export const staffDirectory: StaffMember[] = liveArray(() => {
  const staff = loadActiveCenterStaff();
  if (!staff.length) return SEED_STAFF_DIRECTORY;
  return staff.map((member, index) => ({
    id: member.id,
    name: member.name,
    employeeId: member.employeeCode || member.id,
    designation: member.role,
    department: staffDepartment(member.role),
    email: member.email,
    phone: member.phone,
    avatar: initials(member.name),
    online: index % 3 !== 2,
    lastActive: index % 3 !== 2 ? 'Online' : '2h ago',
    joinedDate: member.joiningDate || '—',
    role: member.role,
  }));
});

