/** Build KPI counts from submission rows (keeps cards in sync with the table). */
export function analyticsFromSubmissions(rows: FormSubmission[]) {
  return {
    submitted: rows.filter((r) => r.status === 'Approved').length,
    rejected: rows.filter((r) => r.status === 'Rejected').length,
    changesRequested: rows.filter((r) => r.status === 'Changes Requested').length,
    pendingReview: rows.filter((r) => r.status === 'Pending Review').length,
    pendingSubmission: rows.filter((r) => r.status === 'Pending Submission').length,
  };
}

