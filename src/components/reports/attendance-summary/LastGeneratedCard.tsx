'use client';

import { motion } from 'framer-motion';
import { Download, FileSpreadsheet } from 'lucide-react';
import { LAST_GENERATED_MOCK } from './types';

type Props = {
  onDownload: () => void;
  dateLabel?: string;
  timeLabel?: string;
  by?: string;
};

export function LastGeneratedCard({
  onDownload,
  dateLabel = LAST_GENERATED_MOCK.dateLabel,
  timeLabel = LAST_GENERATED_MOCK.timeLabel,
  by = LAST_GENERATED_MOCK.by,
}: Props) {
  return (
    <motion.div
      className="asr-last"
      initial={{ opacity: 0, y: 8 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.28 }}
      whileHover={{ y: -2 }}
    >
      <div className="asr-last-main">
        <span className="asr-last-icon" aria-hidden>
          <FileSpreadsheet size={18} />
        </span>
        <div>
          <p className="asr-last-label">Last Generated On</p>
          <div className="asr-last-meta">
            <span>{dateLabel}</span>
            <span>{timeLabel}</span>
            <span>
              <em>Generated By</em> {by}
            </span>
          </div>
        </div>
      </div>
      <motion.button
        type="button"
        className="asr-download-icon"
        aria-label="Download last generated report"
        onClick={onDownload}
        whileHover={{ scale: 1.05 }}
        whileTap={{ scale: 0.96 }}
        transition={{ duration: 0.16 }}
      >
        <Download size={18} />
      </motion.button>
    </motion.div>
  );
}
