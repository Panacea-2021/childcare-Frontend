'use client';

import { useMemo, useState } from 'react';
import { motion } from 'framer-motion';
import {
  ArrowDownUp,
  Baby,
  CalendarRange,
  Download,
  Search,
  Users,
  UserRound,
} from 'lucide-react';
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  Pie,
  PieChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import { Modal } from '@/components/ui/Modal';
import type { GeneratedExcelReport } from '@/components/reports/shared/generatedReport';
import { downloadGeneratedReport } from '@/components/reports/shared/generatedReport';
import { toDisplayDate } from '@/components/reports/attendance-summary/utils';
import './student-count-age.css';

type Props = {
  report: GeneratedExcelReport | null;
  onClose: () => void;
};

const CHART_COLORS = ['#5D5FEF', '#7C83F7', '#4B51E0', '#93A5F8', '#A855F7'];

type SortKey = 'Age Group' | 'Student Count' | 'Percentage';
type SortDir = 'asc' | 'desc';

const PAGE_SIZE = 5;

export function AgeGroupDashboardPreview({ report, onClose }: Props) {
  const [q, setQ] = useState('');
  const [sortKey, setSortKey] = useState<SortKey>('Student Count');
  const [sortDir, setSortDir] = useState<SortDir>('desc');
  const [page, setPage] = useState(0);

  const chartData = useMemo(() => {
    if (!report) return [];
    return report.rows.map((row) => ({
      name: row['Age Group'] ?? '',
      count: Number(row['Student Count'] ?? 0),
      percentage: Number(String(row.Percentage ?? '0').replace('%', '')),
    }));
  }, [report]);

  const filtered = useMemo(() => {
    if (!report) return [] as Record<string, string>[];
    const query = q.trim().toLowerCase();
    let rows = [...report.rows];
    if (query) {
      rows = rows.filter((row) =>
        Object.values(row).some((cell) => cell.toLowerCase().includes(query)),
      );
    }
    rows.sort((a, b) => {
      const av = a[sortKey] ?? '';
      const bv = b[sortKey] ?? '';
      let cmp = 0;
      if (sortKey === 'Student Count' || sortKey === 'Percentage') {
        const an = Number(String(av).replace('%', '')) || 0;
        const bn = Number(String(bv).replace('%', '')) || 0;
        cmp = an - bn;
      } else {
        cmp = av.localeCompare(bv);
      }
      return sortDir === 'asc' ? cmp : -cmp;
    });
    return rows;
  }, [report, q, sortKey, sortDir]);

  const pageCount = Math.max(1, Math.ceil(filtered.length / PAGE_SIZE));
  const safePage = Math.min(page, pageCount - 1);
  const slice = filtered.slice(safePage * PAGE_SIZE, safePage * PAGE_SIZE + PAGE_SIZE);

  const analytics = report?.analytics;
  const total = analytics?.totalStudents ?? report?.recordCount ?? 0;

  const toggleSort = (key: SortKey) => {
    if (sortKey === key) {
      setSortDir((d) => (d === 'asc' ? 'desc' : 'asc'));
    } else {
      setSortKey(key);
      setSortDir(key === 'Age Group' ? 'asc' : 'desc');
    }
    setPage(0);
  };

  if (!report) return null;

  return (
    <Modal
      wide
      open={!!report}
      title="Student Count By Age Group · Dashboard"
      onClose={onClose}
      footer={
        <>
          <button type="button" className="ui-btn ui-btn-outline" onClick={onClose}>
            Close
          </button>
          <button
            type="button"
            className="ui-btn ui-btn-primary"
            onClick={() => downloadGeneratedReport(report)}
          >
            <Download size={16} style={{ marginRight: 8 }} />
            Download Excel
          </button>
        </>
      }
    >
      <div className="scag-dash">
        <div className="scag-meta">
          <span>
            <strong>Admission range:</strong> {toDisplayDate(report.startDate)} –{' '}
            {toDisplayDate(report.endDate)}
          </span>
          <span>
            <strong>Generated by:</strong> {report.generatedBy}
          </span>
          <span className="rp-badge">{total} students</span>
        </div>

        <div className="scag-kpis">
          {[
            {
              label: 'Total Students',
              value: String(total),
              sub: 'Admitted in selected range',
              icon: <Users size={16} />,
            },
            {
              label: 'Average Age',
              value: analytics ? `${analytics.averageAge} yrs` : '—',
              sub: 'Mean age across cohort',
              icon: <CalendarRange size={16} />,
            },
            {
              label: 'Youngest Student',
              value: analytics ? `${analytics.youngestAge.toFixed(1)} yrs` : '—',
              sub: analytics?.youngestLabel ?? '—',
              icon: <Baby size={16} />,
            },
            {
              label: 'Oldest Student',
              value: analytics ? `${analytics.oldestAge.toFixed(1)} yrs` : '—',
              sub: analytics?.oldestLabel ?? '—',
              icon: <UserRound size={16} />,
            },
          ].map((kpi, i) => (
            <motion.div
              key={kpi.label}
              className="scag-kpi"
              initial={{ opacity: 0, y: 10 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: 0.05 * i, duration: 0.28 }}
            >
              <span className="scag-kpi-label" style={{ display: 'inline-flex', gap: 6, alignItems: 'center' }}>
                <span style={{ color: 'var(--color-accent)' }}>{kpi.icon}</span>
                {kpi.label}
              </span>
              <span className="scag-kpi-value">{kpi.value}</span>
              <span className="scag-kpi-sub">{kpi.sub}</span>
            </motion.div>
          ))}
        </div>

        <div className="scag-charts">
          <motion.div
            className="scag-panel"
            initial={{ opacity: 0, scale: 0.98 }}
            animate={{ opacity: 1, scale: 1 }}
            transition={{ delay: 0.12, duration: 0.28 }}
          >
            <h3>Age Group Distribution</h3>
            <div className="scag-chart-wrap">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={chartData} margin={{ top: 8, right: 8, left: -8, bottom: 0 }}>
                  <CartesianGrid strokeDasharray="3 3" stroke="var(--border)" />
                  <XAxis dataKey="name" tick={{ fontSize: 11, fill: 'var(--text-secondary)' }} />
                  <YAxis allowDecimals={false} tick={{ fontSize: 11, fill: 'var(--text-secondary)' }} />
                  <Tooltip
                    contentStyle={{
                      borderRadius: 12,
                      border: '1px solid var(--border)',
                      fontFamily: 'var(--font-body)',
                    }}
                  />
                  <Bar dataKey="count" name="Students" radius={[8, 8, 0, 0]} animationDuration={900}>
                    {chartData.map((_, idx) => (
                      <Cell key={idx} fill={CHART_COLORS[idx % CHART_COLORS.length]} />
                    ))}
                  </Bar>
                </BarChart>
              </ResponsiveContainer>
            </div>
          </motion.div>

          <motion.div
            className="scag-panel"
            initial={{ opacity: 0, scale: 0.98 }}
            animate={{ opacity: 1, scale: 1 }}
            transition={{ delay: 0.18, duration: 0.28 }}
          >
            <h3>Share by Age Band</h3>
            <div className="scag-chart-wrap">
              <ResponsiveContainer width="100%" height="100%">
                <PieChart>
                  <Pie
                    data={chartData}
                    dataKey="count"
                    nameKey="name"
                    innerRadius={58}
                    outerRadius={88}
                    paddingAngle={3}
                    animationDuration={900}
                  >
                    {chartData.map((_, idx) => (
                      <Cell key={idx} fill={CHART_COLORS[idx % CHART_COLORS.length]} />
                    ))}
                  </Pie>
                  <Tooltip
                    contentStyle={{
                      borderRadius: 12,
                      border: '1px solid var(--border)',
                      fontFamily: 'var(--font-body)',
                    }}
                  />
                </PieChart>
              </ResponsiveContainer>
            </div>
          </motion.div>
        </div>

        <motion.div
          className="scag-panel"
          initial={{ opacity: 0, y: 8 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.22, duration: 0.28 }}
        >
          <div className="scag-panel-tools">
            <h3 style={{ flex: 1, margin: 0 }}>Age Group Table</h3>
            <label className="asr-search" style={{ flex: '1 1 220px', maxWidth: 320 }}>
              <Search size={16} aria-hidden />
              <input
                value={q}
                onChange={(e) => {
                  setQ(e.target.value);
                  setPage(0);
                }}
                placeholder="Search age groups…"
                aria-label="Search age groups"
              />
            </label>
            <button
              type="button"
              className="ui-btn ui-btn-outline"
              onClick={() => downloadGeneratedReport(report)}
            >
              <Download size={15} style={{ marginRight: 6 }} />
              Export
            </button>
          </div>

          <div className="mod-scroll" style={{ maxHeight: 280 }}>
            <table className="ui-table">
              <thead>
                <tr>
                  {(['Age Group', 'Student Count', 'Percentage'] as SortKey[]).map((col) => (
                    <th key={col}>
                      <button type="button" className="scag-sort-btn" onClick={() => toggleSort(col)}>
                        {col}
                        <ArrowDownUp size={12} aria-hidden />
                        {sortKey === col ? (
                          <span style={{ fontSize: '0.7rem', opacity: 0.8 }}>
                            {sortDir === 'asc' ? '↑' : '↓'}
                          </span>
                        ) : null}
                      </button>
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {slice.map((row) => (
                  <tr key={row['Age Group']}>
                    <td>{row['Age Group']}</td>
                    <td>{row['Student Count']}</td>
                    <td>{row.Percentage}</td>
                  </tr>
                ))}
                {!slice.length ? (
                  <tr>
                    <td colSpan={3} style={{ textAlign: 'center', color: 'var(--text-secondary)' }}>
                      No age groups match your search.
                    </td>
                  </tr>
                ) : null}
              </tbody>
            </table>
          </div>

          <div className="asr-pager" style={{ marginTop: 12, borderRadius: 12, border: '1px solid var(--border)' }}>
            <span style={{ fontSize: '0.82rem', color: 'var(--text-secondary)' }}>
              Page {safePage + 1} of {pageCount}
            </span>
            <div className="asr-pager-btns">
              <button
                type="button"
                className="ui-btn ui-btn-outline"
                disabled={safePage <= 0}
                onClick={() => setPage((p) => Math.max(0, p - 1))}
              >
                Previous
              </button>
              <button
                type="button"
                className="ui-btn ui-btn-outline"
                disabled={safePage >= pageCount - 1}
                onClick={() => setPage((p) => Math.min(pageCount - 1, p + 1))}
              >
                Next
              </button>
            </div>
          </div>
        </motion.div>
      </div>
    </Modal>
  );
}
